Задание #196 Список сотрудников без подчинённых оказался пустым
Отчёт достался вам от уволившегося аналитика: он должен перечислять сотрудников, у которых нет подчинённых.
Результат пустой, хотя сотрудники без подчинённых в компании есть.
Выведите name (имя сотрудника).

Найдите ошибку в запросе:
SELECT e.name
FROM employees e
WHERE e.id NOT IN (
        SELECT m.manager_id
        FROM employees m
    )
Исправленный запрос:
SELECT name
FROM employees
WHERE manager_id IS NOT NULL; 